                     + "участников. Сохранённые получателем вне приложения копии удалить невозможно.")
            }
            Section("Этот прототип") {
                Text("Данные черновиков, отзывов и профиля хранятся локально. "
                     + "Карты используют Apple Maps; сервер и переписка не подключены.")
            }
        }
    }
}
