import SwiftUI

enum ScreenshotPolicy {
    case terms
    case privacy
}

struct ScreenshotPolicyView: View {
    let policy: ScreenshotPolicy

    var body: some View {
        List {
            Section {
                Text("Ниже приведён текст со снимка исходного Nokhchi. "
                     + "Он описывает исходный сервис, а не работу этого локального прототипа. "
                     + "Контактный адрес из снимка здесь не воспроизведён.")
                    .foregroundStyle(.secondary)
            }
            if policy == .terms { terms } else { privacy }
        }
        .navigationTitle(policy == .terms ? "Условия использования" : "Конфиденциальность")
        .navigationBarTitleDisplayMode(.inline)
    }

    private var terms: some View {
        Group {
            Section("1. Принятие условий") {
                Text("Используя приложение, вы принимаете настоящие условия.")
            }
            Section("2. Контент") {
                Text("Запрещается публикация незаконного, оскорбительного, мошеннического "
                     + "или вводящего в заблуждение контента. Нарушители будут заблокированы.")
            }
            Section("3. Модерация") {
                Text("Все объявления проходят модерацию перед публикацией. "
                     + "Отзывы должны описывать личный опыт. Накрутка оценок, травля, угрозы "
                     + "и нежелательные сообщения запрещены. Для жалобы на сообщение удерживайте "
                     + "его; для блокировки собеседника откройте меню переписки. "
                     + "Жалобы рассматриваются модератором, который может заблокировать нарушителя.")
            }
            Section("4. Ответственность") {
                Text("Приложение является агрегатором и не несёт ответственности "
                     + "за качество услуг третьих лиц.")
            }
            Section("5. Удаление данных") {
                Text("Вы вправе удалить свой аккаунт в любое время через раздел «Профиль».")
            }
        }
    }

    private var privacy: some View {
        Group {
            Section("1. Собираемые данные") {
                Text("Мы собираем: имя, email, фото профиля, данные о местоположении "
                     + "(только при использовании), FCM-токен, опубликованные бизнесы и отзывы, "
                     + "текст и фотографии, которые вы отправляете в переписке.")
            }
            Section("2. Использование данных") {
                Text("Данные используются для авторизации, поиска рядом, уведомлений, общения "
                     + "и модерации. Имя, аватар, отзывы и опубликованные бизнесы видны другим "
                     + "участникам. Email и токены устройства не включаются в публичный профиль.")
            }
            Section("3. Хранение") {
                Text("Данные хранятся в Firebase (Google) с шифрованием в покое и при передаче. "
                     + "Переписка доступна её участникам через авторизацию. "
                     + "Сквозное шифрование не используется. Если вы жалуетесь на конкретное "
                     + "сообщение, его текст и фото передаются модератору. Получатель может "
                     + "сохранить или переслать полученный материал самостоятельно.")
            }
            Section("4. Третьи стороны") {
